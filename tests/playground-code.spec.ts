import { expect, test } from '@playwright/test';

test('Code stays synchronized with styling, document edits, undo and persistence options', async ({ page }) => {
  await page.goto('/playground');
  await expect(page.locator('.flow-card')).toHaveCount(6);
  const viewport = await page.locator('.react-flow__viewport').getAttribute('style');
  await page.getByRole('button', { name: 'Code', exact: true }).click();
  const source = page.getByRole('textbox', { name: 'Generated playground code' });
  await expect(source).toBeVisible();
  await expect(page.getByRole('button', { name: 'Code', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('textbox', { name: 'Default node background', exact: true }).fill('#123456');
  await expect(source).toHaveValue(/#123456/);
  await page.getByRole('textbox', { name: 'Canvas name', exact: true }).fill('Live code canvas');
  await page.getByRole('combobox', { name: 'Generated source file' }).selectOption('canvas.json');
  await expect(source).toHaveValue(/Live code canvas/);
  await page.getByRole('button', { name: 'Undo (⌘Z)', exact: true }).click();
  await expect(source).not.toHaveValue(/Live code canvas/);
  await page.getByRole('combobox', { name: 'Generated source file' }).selectOption('App.tsx');
  await page.getByRole('checkbox', { name: 'Snap to grid', exact: true }).check();
  await expect(source).toHaveValue(/"snap": true/);
  await page.getByLabel('Save options', { exact: true }).click();
  await page.getByRole('checkbox', { name: 'Save view', exact: true }).check();
  await expect(source).toHaveValue(/"rememberView": true/);
  await page.getByRole('checkbox', { name: 'Autosave canvas', exact: true }).check();
  await page.getByRole('combobox', { name: 'Generated source file' }).selectOption('features.ts');
  await expect(source).toHaveValue(/mode: "autosave"/);
  await page.getByRole('checkbox', { name: 'Autosave canvas', exact: true }).uncheck();
  await expect(source).toHaveValue(/mode: "manual"/);
  await page.getByLabel('Save options', { exact: true }).click();
  await page.getByRole('button', { name: 'Flow', exact: true }).click();
  await expect(page.locator('.flow-card').first()).toBeVisible();
  await expect(page.locator('.react-flow__viewport')).toHaveAttribute('style', viewport!);
});

test('Code includes drawings and source files, supports download, and fits mobile', async ({ page }) => {
  await page.goto('/playground');
  await page.getByRole('button', { name: 'Draw', exact: true }).click();
  await page.getByRole('button', { name: 'Pen tool', exact: true }).click();
  const box = (await page.locator('.canvas-stage').boundingBox())!;
  await page.mouse.move(box.x + 100, box.y + 220); await page.mouse.down();
  await page.mouse.move(box.x + 250, box.y + 300); await page.mouse.up();
  await page.getByRole('button', { name: 'Code', exact: true }).click();
  const source = page.getByRole('textbox', { name: 'Generated playground code' });
  await expect(source).toHaveValue(/BoltFlow/);
  const files = page.getByRole('combobox', { name: 'Generated source file' });
  await files.selectOption('drawing.tsx');
  await expect(source).toHaveValue(/id: 'triangle'/);
  await files.selectOption('canvas.json');
  const snapshot = JSON.parse(await source.inputValue());
  expect(snapshot.nodes.some((node: { data: { shape?: string } }) => node.data.shape === 'pen')).toBe(true);
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download file', exact: true }).click();
  expect((await download).suggestedFilename()).toBe('canvas.json');
  await page.getByRole('button', { name: 'Draw', exact: true }).click();
  await expect(page.locator('[data-drawing-shape=pen]')).toHaveCount(1);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Close inspector', exact: true }).click();
  await page.getByRole('button', { name: 'Code', exact: true }).click();
  await expect(source).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
});
